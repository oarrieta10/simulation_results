"""Extract the embedded simulation data from DP Simulation Report HTML exports.

The exported report is ~14 MB, almost all of it bundled viewer code. The actual
results live in a single `window.__STATIC_REPORT_DATA__ = {...}` JSON blob.
This script pulls that blob out so it can be archived, diffed or loaded into the
Simulation Results viewer (which also accepts the raw HTML directly).

Usage:
    python tools/extract_report.py "report.html" [more.html ...] [-o out_dir]
    python tools/extract_report.py *.html --sample samples/sample-reports.js
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

MARKER = "window.__STATIC_REPORT_DATA__="

# Only these top-level keys are needed by the viewer; the rest is board layout.
KEEP_KEYS = ("code", "name", "createTime", "updateTime", "status", "parameters", "reportTemplate", "result")


def extract(html_path: Path) -> dict:
    text = html_path.read_text(encoding="utf-8", errors="replace")
    i = text.find(MARKER)
    if i < 0:
        raise ValueError(f"{html_path.name}: no {MARKER!r} found - is this a DP Simulation Report export?")
    data, _ = json.JSONDecoder().raw_decode(text, i + len(MARKER))
    return data


def slim(data: dict, file_name: str) -> dict:
    out = {k: data.get(k) for k in KEEP_KEYS}
    out["viewConfigs"] = [
        {"code": v.get("code"), "name": v.get("name"), "sqlScript": v.get("sqlScript")}
        for v in data.get("viewConfigs") or []
    ]
    out["__fileName"] = file_name
    return out


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("files", nargs="+", type=Path)
    ap.add_argument("-o", "--out-dir", type=Path, help="write <name>.json per report here (default: next to input)")
    ap.add_argument("--sample", type=Path, help="also write a JS bundle usable as the viewer's built-in sample")
    args = ap.parse_args(argv)

    slims = []
    for f in args.files:
        data = slim(extract(f), f.name)
        slims.append(data)
        out_dir = args.out_dir or f.parent
        out_dir.mkdir(parents=True, exist_ok=True)
        dest = out_dir / (f.stem + ".json")
        dest.write_text(json.dumps(data, ensure_ascii=False, indent=1), encoding="utf-8")
        n = sum(len(v) for v in (data.get("result") or {}).values())
        print(f"{f.name} -> {dest} ({n} result rows)")

    if args.sample:
        args.sample.parent.mkdir(parents=True, exist_ok=True)
        args.sample.write_text(
            "// Generated by tools/extract_report.py - built-in sample data for the viewer.\n"
            "window.SIMRES_SAMPLES = " + json.dumps(slims, ensure_ascii=False) + ";\n",
            encoding="utf-8",
        )
        print(f"sample bundle -> {args.sample}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
